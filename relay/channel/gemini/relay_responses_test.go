func TestGeminiResponsesStreamHandlerReturnsOpenAIResponsesSSE(t *testing.T) {
	gin.SetMode(gin.TestMode)
	recorder := httptest.NewRecorder()
	c, _ := gin.CreateTestContext(recorder)
	c.Request = httptest.NewRequest(http.MethodPost, "/v1/responses", nil)
	c.Set(common.RequestIdKey, "gemini-responses-stream-test")

	oldStreamingTimeout := constant.StreamingTimeout
	constant.StreamingTimeout = 300
	t.Cleanup(func() { constant.StreamingTimeout = oldStreamingTimeout })

	info := newGeminiResponsesRelayInfo(true)
	first := dto.GeminiChatResponse{
		Candidates: []dto.GeminiChatCandidate{
			{
				Content: dto.GeminiChatContent{
					Role: "model",
					Parts: []dto.GeminiPart{
						{Text: "hello"},
					},
				},
			},
		},
		UsageMetadata: dto.GeminiUsageMetadata{
			PromptTokenCount:     2,
			CandidatesTokenCount: 3,
			TotalTokenCount:      5,
		},
	}
	stop := "STOP"
	final := dto.GeminiChatResponse{
		Candidates: []dto.GeminiChatCandidate{
			{
				FinishReason: &stop,
				Content: dto.GeminiChatContent{
					Role:  "model",
					Parts: []dto.GeminiPart{{Text: ""}},
				},
			},
		},
		UsageMetadata: dto.GeminiUsageMetadata{
			PromptTokenCount:     2,
			CandidatesTokenCount: 3,
			TotalTokenCount:      5,
		},
	}
	firstData, err := common.Marshal(first)
	require.NoError(t, err)
	finalData, err := common.Marshal(final)
	require.NoError(t, err)
	streamBody := strings.Join([]string{
		"data: " + string(firstData),
		"",
		"data: " + string(finalData),
		"",
		"data: [DONE]",
		"",
	}, "\n")

	usage, newAPIError := GeminiResponsesStreamHandler(c, info, &http.Response{
		Body: io.NopCloser(strings.NewReader(streamBody)),
	})
	require.Nil(t, newAPIError)
	require.NotNil(t, usage)
	assert.Equal(t, 5, usage.TotalTokens)

	got := recorder.Body.String()
	assert.Equal(t, "text/event-stream", recorder.Header().Get("Content-Type"))
	assert.Contains(t, got, `event: response.created`)
	assert.Contains(t, got, `event: response.output_text.delta`)
	assert.Contains(t, got, `"delta":"hello"`)
	assert.Contains(t, got, `event: response.completed`)
	assert.Contains(t, got, `"input_tokens":2`)
	assert.Contains(t, got, `"output_tokens":3`)
	assert.NotContains(t, got, `"choices"`)
	assert.NotContains(t, got, `"candidates"`)
	requireOrderedGeminiResponsesSubstrings(t, got,
		`event: response.created`,
		`event: response.output_item.added`,
		`event: response.output_text.delta`,
		`event: response.output_text.done`,
		`event: response.completed`,
	)
}

func newGeminiResponsesRelayInfo(isStream bool) *relaycommon.RelayInfo {
	return &relaycommon.RelayInfo{
		IsStream:        isStream,
		RelayMode:       relayconstant.RelayModeResponses,
		RelayFormat:     types.RelayFormatOpenAIResponses,
		RequestURLPath:  "/v1/responses",
		DisablePing:     true,
		OriginModelName: "gemini-test",
		ChannelMeta: &relaycommon.ChannelMeta{
			UpstreamModelName: "gemini-test",
		},
	}
}

type failingReadCloser struct {
	closed bool
}

func (r *failingReadCloser) Read([]byte) (int, error) {
	return 0, errors.New("read failed")
}

func (r *failingReadCloser) Close() error {
	r.closed = true
	return nil
}

func requireOrderedGeminiResponsesSubstrings(t *testing.T, s string, parts ...string) {
	t.Helper()
	offset := 0
	for _, part := range parts {
		idx := strings.Index(s[offset:], part)
		require.NotEqualf(t, -1, idx, "missing %q after byte offset %d", part, offset)
		offset += idx + len(part)
	}
}

type partialReadCloser struct {
	data   []byte
	offset int
	err    error
}

func (r *partialReadCloser) Read(p []byte) (int, error) {
	if r.offset < len(r.data) {
		n := copy(p, r.data[r.offset:])
		r.offset += n
		return n, nil
	}
	return 0, r.err
}

func (r *partialReadCloser) Close() error {
	return nil
}

func TestGeminiResponsesStreamHandlerOnUnexpectedEOFBeforeContent(t *testing.T) {
	gin.SetMode(gin.TestMode)
	recorder := httptest.NewRecorder()
	c, _ := gin.CreateTestContext(recorder)
	c.Request = httptest.NewRequest(http.MethodPost, "/v1/responses", nil)
	c.Set(common.RequestIdKey, "gemini-responses-stream-err-test")

	oldStreamingTimeout := constant.StreamingTimeout
	constant.StreamingTimeout = 300
	t.Cleanup(func() { constant.StreamingTimeout = oldStreamingTimeout })

	info := newGeminiResponsesRelayInfo(true)
	// Upstream returns 2 chunks without candidates, then unexpected EOF before any content
	streamBody := "data: {\"modelVersion\":\"v1\"}\n\ndata: {\"modelVersion\":\"v1\"}\n\n"
	body := &partialReadCloser{
		data: []byte(streamBody),
		err:  io.ErrUnexpectedEOF,
	}

	usage, newAPIError := GeminiResponsesStreamHandler(c, info, &http.Response{
		Body: body,
	})
	require.NotNil(t, newAPIError, "expected non-nil newAPIError so Relay can failover")
	assert.Nil(t, usage)
	assert.Empty(t, recorder.Body.String(), "expected no data written to client when failing before content")
	assert.Equal(t, "retry", service.DecideRelayRetry(c, newAPIError, 1).Action,
		"a drop before the first content event must stay retryable, otherwise the failover never runs")
}

// silentReadCloser answers like an upstream that accepted the stream and then
// said nothing: Read blocks until Close, which is what an aborted attempt does.
type silentReadCloser struct {
	closed chan struct{}
	once   sync.Once
}

func (r *silentReadCloser) Read([]byte) (int, error) {
	<-r.closed
	return 0, errors.New("read on closed body")
}

func (r *silentReadCloser) Close() error {
	r.once.Do(func() { close(r.closed) })
	return nil
}

func TestGeminiResponsesStreamHandlerAbortsAttemptThatNeverStartsAnswering(t *testing.T) {
	gin.SetMode(gin.TestMode)
	recorder := httptest.NewRecorder()
	c, _ := gin.CreateTestContext(recorder)
	c.Request = httptest.NewRequest(http.MethodPost, "/v1/responses", nil)
	c.Set(common.RequestIdKey, "gemini-responses-first-token-timeout-test")

	previousToken, previousContent := operation_setting.FirstTokenTimeoutSeconds, operation_setting.FirstContentTimeoutSeconds
	operation_setting.FirstTokenTimeoutSeconds = 1
	operation_setting.FirstContentTimeoutSeconds = 0
	previousStreamingTimeout := constant.StreamingTimeout
	constant.StreamingTimeout = 300
	t.Cleanup(func() {
		operation_setting.FirstTokenTimeoutSeconds = previousToken
		operation_setting.FirstContentTimeoutSeconds = previousContent
		constant.StreamingTimeout = previousStreamingTimeout
	})

	info := newGeminiResponsesRelayInfo(true)
	body := &silentReadCloser{closed: make(chan struct{})}
	streamed := make(chan *types.NewAPIError, 1)
	go func() {
		_, apiErr := GeminiResponsesStreamHandler(c, info, &http.Response{Body: body})
		streamed <- apiErr
	}()

	select {
	case apiErr := <-streamed:
		require.NotNil(t, apiErr)
		assert.Contains(t, apiErr.Error(), "first token timeout")
		assert.Equal(t, "retry", service.DecideRelayRetry(c, apiErr, 1).Action)
		assert.Empty(t, recorder.Body.String(), "an aborted attempt must not write anything to the client")
	case <-time.After(10 * time.Second):
		t.Fatal("the first-token budget never aborted the attempt")
	}
	assert.Equal(t, relaycommon.StreamEndReasonTimeout, info.StreamStatus.EndReason,
		"the stream status must report the budget, not a transport error")
}

func TestGeminiResponsesStreamHandlerOnUnexpectedEOFAfterContent(t *testing.T) {
	gin.SetMode(gin.TestMode)
	recorder := httptest.NewRecorder()
	c, _ := gin.CreateTestContext(recorder)
	c.Request = httptest.NewRequest(http.MethodPost, "/v1/responses", nil)
	c.Set(common.RequestIdKey, "gemini-responses-stream-err-after-content-test")

	oldStreamingTimeout := constant.StreamingTimeout
	constant.StreamingTimeout = 300
	t.Cleanup(func() { constant.StreamingTimeout = oldStreamingTimeout })

	info := newGeminiResponsesRelayInfo(true)
	first := dto.GeminiChatResponse{
		Candidates: []dto.GeminiChatCandidate{
			{
				Content: dto.GeminiChatContent{
					Role: "model",
					Parts: []dto.GeminiPart{
						{Text: "hello"},
					},
				},
			},
		},
	}
	firstData, err := common.Marshal(first)
	require.NoError(t, err)

	streamBody := "data: " + string(firstData) + "\n\n"
	body := &partialReadCloser{
		data: []byte(streamBody),
		err:  io.ErrUnexpectedEOF,
	}

	usage, newAPIError := GeminiResponsesStreamHandler(c, info, &http.Response{
		Body: body,
	})
	require.Nil(t, newAPIError, "cannot failover after content has been written")
	assert.NotNil(t, usage)

	got := recorder.Body.String()
	assert.Contains(t, got, `event: response.created`)
	assert.Contains(t, got, `event: response.output_text.delta`)
	assert.Contains(t, got, `event: error`)
	assert.Contains(t, got, `event: response.failed`)
}
